"""PREREG 12.3: the lint of SUMMARY.md outside quoted scan output."""

from __future__ import annotations

import re
from collections.abc import Collection, Iterator
from dataclasses import dataclass
from typing import Final

FENCES: Final = ("```", "~~~")
QUOTE_PREFIX: Final = ">"
BANNED_WORDS: Final = (
    "bug",
    "bugs",
    "buggy",
    "clean",
    "safe",
    "score",
    "authored",
    "wrote",
    "agent-written",
    "AI-written",
)
BANNED_PHRASES: Final = ("written by", "generated by")
UPPER_CASE_WORDS: Final = ("PASS",)
PERCENT: Final = "%"
_INLINE_CODE = re.compile(r"(`+)(.+?)\1")
_FRACTION = re.compile(r"(?<![\w/.])(\d+)/(\d+)(?![\w/])")
_AGENT_BY = re.compile(r"(?<!\w)by\s+(?:copilot|claude|codex)(?!\w)", re.IGNORECASE)


def _whole(word: str, flags: int = 0) -> re.Pattern[str]:
    return re.compile(rf"(?<!\w){re.escape(word)}(?!\w)", flags)


_CASELESS: Final = tuple((word, _whole(word, re.IGNORECASE)) for word in (*BANNED_WORDS, *BANNED_PHRASES))
_CASED: Final = tuple((word, _whole(word)) for word in UPPER_CASE_WORDS)


@dataclass(frozen=True)
class Violation:
    line: int
    rule: str
    text: str

    def render(self) -> str:
        return f"SUMMARY.md:{self.line}: {self.rule}: {self.text}"


def checked_lines(markdown: str) -> Iterator[tuple[int, str]]:
    """Every line outside fenced blocks and quotes, with its inline code spans removed."""
    fence: str | None = None
    for number, line in enumerate(markdown.split("\n"), start=1):
        stripped = line.lstrip()
        if fence is not None:
            if stripped.startswith(fence):
                fence = None
            continue
        opening = next((marker for marker in FENCES if stripped.startswith(marker)), None)
        if opening is not None:
            fence = opening
            continue
        if stripped.startswith(QUOTE_PREFIX):
            continue
        yield number, _INLINE_CODE.sub(" ", line)


def lint(markdown: str, fractions: Collection[str]) -> list[Violation]:
    allowed = set(fractions)
    violations: list[Violation] = []
    for number, line in checked_lines(markdown):
        for word, pattern in (*_CASELESS, *_CASED):
            if pattern.search(line):
                violations.append(Violation(number, "banned word", word))
        if match := _AGENT_BY.search(line):
            violations.append(Violation(number, "banned word", match.group(0)))
        if PERCENT in line:
            violations.append(Violation(number, "percent sign", PERCENT))
        for match in _FRACTION.finditer(line):
            if match.group(0) not in allowed:
                violations.append(Violation(number, "fraction not in summary.json", match.group(0)))
    return violations
